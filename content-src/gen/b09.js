    idea: '两次二分可以合成一次。关键洞察是：**在任何一次二分的中点上，左半段和右半段里必有且仅有一段是完全有序的**（因为数组只在某一处断开）。\n\n于是每一步这样做：\n1. 算出 mid，先看 `nums[mid] == target`，命中直接返回；\n2. 判断哪半边有序：如果 `nums[left] <= nums[mid]`，说明**左半段有序**；否则右半段有序；\n3. 在有序的那半段里判断 target 在不在：\n   - 左半有序时：若 `nums[left] <= target && target < nums[mid]`，说明 target 在左半，`right = mid - 1`；否则去右半，`left = mid + 1`；\n   - 右半有序时：若 `nums[mid] < target && target <= nums[right]`，去右半，`left = mid + 1`；否则去左半，`right = mid - 1`。\n\n为什么这个判断一定正确？因为**有序的那半段可以用区间端点直接判断「在不在范围内」**，而不有序的那半段没法这样判断。所以只要判断有序半边，答案就唯一确定了，另一半必然可以整段丢掉。\n\n为什么这是最优？一次遍历，O(log n)，无额外空间，也没有第一次找旋转点的开销。这是本题的标准答案。\n\n**三个最容易写错的点（这题的错误率极高）**：\n1. `nums[left] <= nums[mid]` 里的 `<=` 不能写成 `<`。当 `left == mid`（区间只剩两个元素）时，`<` 会误判成「右半有序」，然后走进错误分支。\n2. 判断 target 在左半时条件是 `target < nums[mid]`（严格小于），因为 `== nums[mid]` 已经在第 1 步返回了。写成 `<=` 虽然也对，但要知道为什么。\n3. 两个分支里的 `right = mid - 1` / `left = mid + 1` 一定同时出现——如果只写一个，会死循环。\n\n复杂度 O(log n) 时间，O(1) 空间。',
