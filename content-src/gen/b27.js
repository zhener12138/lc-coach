      "    public int hammingDistance(int x, int y) {",
      "        int d = x ^ y;",
      "        int cnt = 0;",
      "        for (int b = 0; b < 32; b++) {",
      "            if (((d >> b) & 1) == 1) cnt++;",
      "        }",
      "        return cnt;",
      "    }",
      "}"
