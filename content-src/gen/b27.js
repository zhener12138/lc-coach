      "2. cnt = 0",
      "3. 对 b 从 0 到 31：",
      "     如果 (d 右移 b) 位与 1 等于 1：cnt 加 1",
      "4. return cnt",
      "",
      "汉明距离等于两数异或结果中 1 的个数",
      "固定循环 32 次，与差异多少无关",
      "复杂度：时间 O(32) 即 O(1)；空间 O(1)"
